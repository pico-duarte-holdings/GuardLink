function formatValue(key: string, val: any): string {
  if (val === null || val === undefined || val === '') return '';
  if (typeof val === 'boolean') return val ? 'YES' : 'NO';
  return String(val).toUpperCase();
}

/**
 * Generates a fillable-style PDF of a player's intake data.
 * All values are UPPERCASE for Army Recruiter Zone copy/paste.
 */
export function exportIntakePDF(data: IntakeFields, playerName: string): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'letter' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 15;
  const fieldWidth = pageWidth - margin * 2;
  let y = 20;

  // Title
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('GUARDLINK — RECRUIT INTAKE / ONBOARDING FORM', margin, y);
  y += 7;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(`GENERATED: ${new Date().toISOString().split('T')[0].toUpperCase()}`, margin, y);
  doc.text(`PLAYER: ${playerName.toUpperCase()}`, margin + 80, y);
  y += 4;
  doc.setDrawColor(200, 175, 55);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  // Fields
  doc.setFontSize(8);
  for (const [key, label] of FIELD_ORDER) {
    const val = formatValue(key, data[key]);

    // Check if we need a new page
    if (y > 260) {
      doc.addPage();
      y = 20;
    }

    // Label
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(100, 100, 100);
    doc.text(label, margin, y);
    y += 4;

    // Value box (light underline for copy/paste feel)
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(0, 0, 0);

    // Handle long text (wrap)
    if (val.length > 80) {
      const lines = doc.splitTextToSize(val, fieldWidth);
      doc.text(lines, margin, y);
      y += lines.length * 4;
    } else {
      doc.text(val || '________________________________________', margin, y);
      y += 4;
    }

    // Separator line
    doc.setDrawColor(220, 220, 220);
    doc.setLineWidth(0.2);
    doc.line(margin, y, pageWidth - margin, y);
    y += 5;
  }

  // Footer
  if (y > 250) { doc.addPage(); y = 20; }
  y += 5;
  doc.setFontSize(7);
  doc.setTextColor(150, 150, 150);
  doc.text('THIS DOCUMENT WAS GENERATED BY GUARDLINK RECRUITING PLATFORM. ALL DATA IS UPPERCASE FOR ARZ PROCESSING.', margin, y);

  const fileName = `INTAKE_${(data.lastName || 'UNKNOWN').toUpperCase()}_${(data.firstName || '').toUpperCase()}_${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(fileName);
}
